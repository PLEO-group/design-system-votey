function compareNames(left, right) {
  if (left < right) return -1;
  if (left > right) return 1;
  return 0;
}

function normalizeName(value) {
  return value
    .replaceAll("_", "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase();
}

function getSvgFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = path.join(directory, entry.name);

    if (entry.isDirectory()) return getSvgFiles(entryPath);
    return entry.isFile() && path.extname(entry.name).toLowerCase() === ".svg"
      ? [entryPath]
      : [];
  });
}

function createAssetEntry(group, filePath) {
  const fileName = path.basename(filePath, path.extname(filePath));
  const withoutPrefix = fileName.replace(group.stripPrefix, "");
  const semanticName = group.stripSuffix
    ? withoutPrefix.replace(group.stripSuffix, "")
    : withoutPrefix;

  return {
    filePath,
    kind: group.kind,
    name: `${group.namespace}-${normalizeName(semanticName)}`,
    path: path
      .relative(path.join(projectRoot, "assets"), filePath)
      .split(path.sep)
      .join("/"),
  };
}

function assertUniqueNames(entries, kind) {
  const pathsByName = new Map();

  for (const entry of entries) {
    const existingPath = pathsByName.get(entry.name);

    if (existingPath) {
      throw new Error(
        `Duplicate ${kind} name "${entry.name}" for ${existingPath} and ${entry.filePath}.`,
      );
    }

    pathsByName.set(entry.name, entry.filePath);
  }
}

export function getAssetEntries() {
  const entries = assetGroups
    .flatMap((group) =>
      getSvgFiles(group.directory).map((filePath) =>
        createAssetEntry(group, filePath),
      ),
    )
    .sort((left, right) => compareNames(left.name, right.name));
  const icons = entries.filter(({ kind }) => kind === "icon");
  const illustrations = entries.filter(
    ({ kind }) => kind === "illustration",
  );

  assertUniqueNames(icons, "icon");
  assertUniqueNames(illustrations, "illustration");
  assertUniqueNames(entries, "SVG asset");

  return { icons, illustrations };
}

function renderNames(exportName, entries) {
  const names = entries.map(({ name }) => `  ${JSON.stringify(name)},`);

  return `export const ${exportName} = [\n${names.join("\n")}\n] as const;`;
}

function renderRegistryEntries(exportName, nameType, entries) {
  const registryEntries = entries.map(
    ({ name, path: assetPath }) =>
      `  { name: ${JSON.stringify(name)}, path: ${JSON.stringify(assetPath)} },`,
  );

  return `export const ${exportName}: readonly VoteySvgRegistryEntry<${nameType}>[] = [\n${registryEntries.join("\n")}\n];`;
}

export function buildAssetTypesSource() {
  const { icons, illustrations } = getAssetEntries();

  return `// This file is generated by scripts/generate-asset-types.mjs.
// Do not edit it manually. Source SVG files remain unchanged.

${renderNames("VoteyIconNames", icons)}

export type VoteyIcon = (typeof VoteyIconNames)[number];

export interface VoteySvgRegistryEntry<Name extends string> {
  readonly name: Name;
  readonly path: string;
}

${renderRegistryEntries("VoteyIconRegistryEntries", "VoteyIcon", icons)}

${renderNames("VoteyIllustrationNames", illustrations)}

export type VoteyIllustration = (typeof VoteyIllustrationNames)[number];

${renderRegistryEntries(
  "VoteyIllustrationRegistryEntries",
  "VoteyIllustration",
  illustrations,
)}
`;
}

export function generateAssetTypes({ check = false } = {}) {
  const source = buildAssetTypesSource();

  if (check) {
    if (!existsSync(assetTypesOutputPath)) {
      throw new Error(
        "Generated asset types are missing. Run npm run generate:asset-types.",
      );
    }

    if (readFileSync(assetTypesOutputPath, "utf8") !== source) {
      throw new Error(
        "Generated asset types are stale. Run npm run generate:asset-types.",
      );
    }

    return;
  }

  writeFileSync(assetTypesOutputPath, source, "utf8");
}

const isDirectRun =
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isDirectRun) {
  generateAssetTypes({ check: process.argv.includes("--check") });
}
